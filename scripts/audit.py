"""Read-only audit of the six supplied files; truth is inspected only for schema statistics."""

import csv, json, collections, math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
report = {}
ids = {
    "consignments": "consignment_id",
    "drivers": "driver_id",
    "vehicles": "vehicle_id",
    "delivery_history": "consignment_id",
    "ground_truth_sample": "consignment_id",
    "areas": "area_name",
}
numeric = {
    "weight_kg",
    "length_cm",
    "width_cm",
    "height_cm",
    "pieces",
    "cod_amount_aed",
    "attempt_number",
    "experience_months",
    "max_weight_kg",
    "max_volume_m3",
    "fixed_cost_aed_day",
    "cost_per_km_aed",
    "event_lat",
    "event_lng",
    "true_lat",
    "true_lng",
    "centroid_lat",
    "centroid_lng",
}
for name, key in ids.items():
    rows = list(
        csv.DictReader((ROOT / "data" / f"{name}.csv").open(encoding="utf-8-sig"))
    )
    counts = collections.Counter(r[key] for r in rows)
    schema = {}
    for col in rows[0]:
        vals = [r[col] for r in rows if r[col].strip()]
        invalid = []
        if col in numeric:
            for i, r in enumerate(rows, 2):
                if r[col]:
                    try:
                        n = float(r[col])
                        assert math.isfinite(n)
                        if col not in {
                            "event_lat",
                            "event_lng",
                            "true_lat",
                            "true_lng",
                            "centroid_lat",
                            "centroid_lng",
                        }:
                            assert n >= 0
                    except (ValueError, AssertionError):
                        invalid.append({"line": i, "value": r[col]})
        schema[col] = {
            "inferred_type": "number" if col in numeric else "string",
            "missing": len(rows) - len(vals),
            "invalid_numeric": invalid,
        }
    categorical = {
        c: dict(collections.Counter(r[c] for r in rows))
        for c in rows[0]
        if c
        in {
            "city",
            "area",
            "status",
            "type",
            "licence_type",
            "handling",
            "outcome",
            "failure_reason",
            "slot_start",
            "slot_end",
            "payment_type",
            "refrigerated",
            "emirate",
            "pieces",
        }
    }
    report[name] = {
        "rows": len(rows),
        "schema": schema,
        "duplicate_ids": {k: v for k, v in counts.items() if v > 1},
        "categories": categorical,
    }
    invalid_lines = {
        v["line"] for field in schema.values() for v in field["invalid_numeric"]
    }
    report[name]["row_profiles"] = [
        {
            "row_key": f"{name}:{line}",
            "record_id": r[key],
            "disposition": (
                "EVALUATION_ONLY"
                if name == "ground_truth_sample"
                else (
                    "AREA_REFERENCE_ONLY"
                    if name == "areas"
                    else (
                        "REVIEW_PROFILE_ISSUES"
                        if line in invalid_lines or counts[r[key]] > 1
                        else "PROFILED"
                    )
                )
            ),
            "numeric_problem": line in invalid_lines,
            "duplicate_key": counts[r[key]] > 1,
        }
        for line, r in enumerate(rows, 2)
    ]
    if name in {"consignments", "delivery_history"}:
        phones = collections.Counter(
            r["customer_phone"] for r in rows if r["customer_phone"]
        )
        addresses = collections.Counter(
            tuple(
                r[k].strip().casefold()
                for k in ["address_line_1", "address_line_2", "area", "city"]
            )
            for r in rows
        )
        report[name]["repeat_phone_groups"] = sum(v > 1 for v in phones.values())
        report[name]["repeat_exact_address_groups"] = sum(
            v > 1 for v in addresses.values()
        )
(ROOT / "outputs/data_audit.json").write_text(
    json.dumps(report, indent=2, ensure_ascii=False)
)
lines = [
    "# Source data audit",
    "",
    "Generated by `python scripts/audit.py`. The audit leaves source rows unchanged. The v2 brief takes precedence.",
    "",
]
for name, r in report.items():
    lines += [
        f"## {name}",
        f"{r['rows']} rows. Duplicate keys: {json.dumps(r['duplicate_ids'])}.",
        "",
        "| Field | Inferred type | Missing | Invalid numeric |",
        "|---|---|---:|---|",
    ]
    for c, s in r["schema"].items():
        lines.append(
            f"| {c} | {s['inferred_type']} | {s['missing']} | {json.dumps(s['invalid_numeric'])} |"
        )
    for c, vals in r["categories"].items():
        if c != "area":
            lines += ["", f"{c}: `{json.dumps(vals,ensure_ascii=False)}`"]
    if "repeat_phone_groups" in r:
        lines += [
            "",
            f"Repeated masked-phone groups: {r['repeat_phone_groups']}; repeated exact-address groups: {r['repeat_exact_address_groups']}. A masked phone can support a match, but cannot identify a destination alone.",
        ]
    lines += [""]
lines += [
    "## Operational consequences",
    "",
    "Hold every row that shares a duplicate consignment ID, even when the values match. Correct negative or missing package values at source and confirm nonstandard slots. Normalize known city aliases; review conflicting emirates. V01 is a motorbike marked refrigerated, but chilled parcels require a chilled van. Confirm a building location before routing an area-centre candidate. The historical failure rate describes this sample and has not been calibrated as a forecast. `outputs/validation.json` records problems and import decisions for each row.",
]
(ROOT / "docs/data_audit.md").write_text("\n".join(lines) + "\n")
print({k: v["rows"] for k, v in report.items()})
